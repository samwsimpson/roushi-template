// ─── Brain: maintenance_runs (cron-fire log) ───────────────────────
// Every invocation of `runMaintenance(kind)` writes a row. Lets us show
// "Decay: last ran 6h ago, 0 findings" even when no goal was created —
// closes the visibility gap Sam hit on first cron night ("did the cron
// fire?" had no answer because zero-finding runs produced nothing).

export const maintenanceKindEnum = pgEnum("maintenance_kind", [
  "decay",
  "dedupe",
  "audit-edges",
  "contradictions",
]);

export const maintenanceRuns = pgTable(
  "maintenance_runs",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    kind: maintenanceKindEnum("kind").notNull(),
    ranAt: timestamp("ran_at", { withTimezone: true }).defaultNow().notNull(),
    findingsCount: integer("findings_count").notNull(),
    threshold: integer("threshold").notNull(),
    exceededThreshold: boolean("exceeded_threshold").notNull(),
    /** "created" | "updated" | "completed" | "noop" — mirrors upsertSystemGoal output. */
    goalAction: text("goal_action").notNull(),
    goalId: uuid("goal_id"),
    durationMs: integer("duration_ms").notNull().default(0),
  },
  (t) => [
    index("maintenance_runs_kind_idx").on(t.kind),
    index("maintenance_runs_ran_at_idx").on(t.ranAt),
  ],
);

