// ─── Brain: playbooks (recurring instructions / standing rules) ──

export const playbooks = pgTable(
  "playbooks",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    slug: varchar("slug", { length: 128 }).notNull(),
    name: text("name").notNull(),
    description: text("description").notNull().default(""),
    trigger: playbookTriggerEnum("trigger").notNull(),
    // Optional structured filter — only fire playbook when context matches.
    // e.g. { entityType: "product", clientWork: false } restricts to non-client products.
    filter: jsonb("filter").$type<Record<string, unknown>>().default({}).notNull(),
    // Ordered free-text instructions for the agent (Claude / Cursor / etc.) to follow
    // when this playbook fires. Each step is one action.
    actions: text("actions").array().notNull(),
    // Optional list of entity slugs this playbook applies to. Empty array = all matching.
    // e.g. ["kodori", "roushi"] limits the playbook to those two products.
    appliesToSlugs: text("applies_to_slugs").array().notNull().default(sql`'{}'::text[]`),
    active: boolean("active").notNull().default(true),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [
    uniqueIndex("playbooks_slug_idx").on(t.slug),
    index("playbooks_trigger_idx").on(t.trigger),
    index("playbooks_active_idx").on(t.active),
  ],
);

// ─── Brain: playbook invocations + per-action approval state ─────

export const playbookInvocations = pgTable(
  "playbook_invocations",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    playbookId: uuid("playbook_id")
      .notNull()
      .references(() => playbooks.id, { onDelete: "cascade" }),
    // Snapshot of the trigger event that fired this invocation.
    eventTrigger: playbookTriggerEnum("event_trigger").notNull(),
    eventContext: jsonb("event_context").$type<Record<string, unknown>>().default({}).notNull(),
    // Optional — the entity the event was about (e.g. the project that was created).
    entityId: uuid("entity_id").references(() => entities.id, { onDelete: "set null" }),
    status: invocationStatusEnum("status").notNull().default("pending"),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [
    index("playbook_invocations_playbook_idx").on(t.playbookId),
    index("playbook_invocations_status_idx").on(t.status),
    index("playbook_invocations_created_idx").on(t.createdAt),
  ],
);

export const invocationActions = pgTable(
  "invocation_actions",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    invocationId: uuid("invocation_id")
      .notNull()
      .references(() => playbookInvocations.id, { onDelete: "cascade" }),
    actionIndex: integer("action_index").notNull(),
    actionText: text("action_text").notNull(),
    status: invocationActionStatusEnum("status").notNull().default("pending"),
    notes: text("notes"),
    /** Who/what marked this action complete: "manual" (a human) or an agent id. */
    completedBy: varchar("completed_by", { length: 128 }),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [
    uniqueIndex("invocation_actions_unique_idx").on(t.invocationId, t.actionIndex),
    index("invocation_actions_status_idx").on(t.status),
  ],
);

