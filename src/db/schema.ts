// ─── Brain: entities (graph nodes) ─────────────────────────────────

export const entities = pgTable(
  "entities",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    slug: varchar("slug", { length: 128 }).notNull(),
    type: entityTypeEnum("type").notNull(),
    name: text("name").notNull(),
    description: text("description").notNull().default(""),
    frontmatter: jsonb("frontmatter").$type<Record<string, unknown>>().default({}).notNull(),
    sourcePath: text("source_path"), // path to the source markdown file
    embedding: vector("embedding"), // 1536-dim for text-embedding-3-small
    searchVector: tsvector("search_vector"), // generated by trigger from name + description
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
    lastValidatedAt: timestamp("last_validated_at", { withTimezone: true }).defaultNow().notNull(),
    createdBy: uuid("created_by").references(() => users.id, { onDelete: "set null" }),
  },
  (t) => [
    uniqueIndex("entities_slug_idx").on(t.slug),
    index("entities_type_idx").on(t.type),
    index("entities_last_validated_idx").on(t.lastValidatedAt),
    // pgvector HNSW index — must be created via raw SQL in migration
    // tsvector GIN index — must be created via raw SQL in migration
  ],
);

// ─── Brain: edges (typed relationships) ────────────────────────────

export const edges = pgTable(
  "edges",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    fromEntityId: uuid("from_entity_id")
      .notNull()
      .references(() => entities.id, { onDelete: "cascade" }),
    toEntityId: uuid("to_entity_id")
      .notNull()
      .references(() => entities.id, { onDelete: "cascade" }),
    relation: edgeRelationEnum("relation").notNull(),
    declaredByEntityId: uuid("declared_by_entity_id").references(() => entities.id, {
      onDelete: "cascade",
    }),
    context: text("context"), // snippet of markdown around the declaration
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [
    uniqueIndex("edges_unique_idx").on(t.fromEntityId, t.toEntityId, t.relation),
    index("edges_from_idx").on(t.fromEntityId),
    index("edges_to_idx").on(t.toEntityId),
    index("edges_relation_idx").on(t.relation),
  ],
);

